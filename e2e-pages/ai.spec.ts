import { test, expect } from '@playwright/test';
const endpoint = 'https://jarvis-api.example';
const headers = { 'Access-Control-Allow-Origin': 'http://127.0.0.1:4173', 'Access-Control-Allow-Headers': 'Content-Type', 'Access-Control-Allow-Methods': 'GET, POST, OPTIONS' };
test.beforeEach(async ({ page }) => { await page.addInitScript(() => localStorage.setItem('jarvis.view.v1', 'chat')); });
test('conecta backend, envia contexto recente, mantém notas locais e restaura a conexão', async ({ page }) => {
  const conversations: { message: string; context: { role: string; content: string }[] }[] = [];
  await page.route(`${endpoint}/**`, async route => {
    if (route.request().method() === 'OPTIONS') return route.fulfill({ status: 204, headers });
    if (route.request().url().endsWith('/api/health')) return route.fulfill({ headers, json: { status: 'ok', provider: 'groq', version: '0.1.0', ai: { configured: true, provider: 'groq', model: 'test-model' } } });
    const body = route.request().postDataJSON(); conversations.push(body);
    await route.fulfill({ headers, json: { id: `ai-${conversations.length}`, message: conversations.length === 1 ? 'React cria interfaces com componentes.' : 'Em resumo: componentes constroem a interface.', command: 'conversation', provider: 'groq', createdAt: new Date().toISOString() } });
  });
  await page.goto('./');
  await page.getByRole('button', { name: 'Preferências' }).click();
  await page.getByRole('textbox', { name: 'Endereço do backend' }).fill(endpoint);
  await page.getByRole('button', { name: 'Conectar IA', exact: true }).click();
  await expect(page.getByRole('dialog').getByRole('status')).toContainText('Backend verificado');
  await expect(page.getByRole('dialog')).toContainText('IA configurada · Groq');
  await page.getByRole('button', { name: 'Fechar janela' }).click();
  const send = async (message: string) => {
    await page.getByRole('textbox', { name: 'Sua mensagem para JARVIS' }).fill(message);
    await page.getByRole('button', { name: 'Enviar mensagem' }).click();
  };
  await send('Explique React');
  await expect(page.getByRole('log')).toContainText('React cria interfaces com componentes.');
  expect(conversations[0].context).toEqual([]);
  await send('Resuma isso numa frase');
  await expect(page.getByRole('log')).toContainText('Em resumo: componentes constroem a interface.');
  expect(conversations[1].context).toEqual([{ role: 'user', content: 'Explique React' }, { role: 'assistant', content: 'React cria interfaces com componentes.' }]);
  await send('anotar estudar React');
  await expect(page.getByRole('log')).toContainText('Nota salva: estudar React');
  expect(conversations).toHaveLength(2);
  await page.reload();
  await page.getByRole('button', { name: 'Preferências' }).click();
  await expect(page.getByRole('dialog')).toContainText('IA configurada · Groq');
  await page.getByRole('button', { name: 'Fechar janela' }).click();
  expect(await page.locator('.message-assistant[data-provider="groq"]').count()).toBe(2);
  await page.getByRole('button', { name: 'Preferências' }).click();
  await expect(page.getByRole('textbox', { name: 'Endereço do backend' })).toHaveValue(endpoint);
  await page.getByRole('button', { name: 'Usar somente comandos locais' }).click();
  await page.getByRole('button', { name: 'Fechar janela' }).click();
  await send('notas');
  await expect(page.getByRole('log')).toContainText('1. estudar React');
  await send('Me explique TypeScript');
  await expect(page.getByRole('log')).toContainText('Ainda não entendo esse pedido');
  expect(conversations).toHaveLength(2);
});
test('não afirma IA disponível para endereço inseguro ou backend sem modelo', async ({ page }) => {
  await page.route(`${endpoint}/api/health`, route => route.fulfill({ headers, json: { status: 'ok', provider: 'local', version: '0.1.0' } }));
  await page.goto('./');
  await page.getByRole('button', { name: 'Preferências' }).click();
  await page.getByRole('textbox', { name: 'Endereço do backend' }).fill('http://192.168.1.10:3001');
  await page.getByRole('button', { name: 'Conectar IA', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('Use HTTPS');
  await page.getByRole('textbox', { name: 'Endereço do backend' }).fill(endpoint);
  await page.getByRole('button', { name: 'Conectar IA', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('ainda não tem um modelo configurado');
  expect(await page.evaluate(() => localStorage.getItem('jarvis.backend.v1'))).toBeNull();
});
test('backend indisponível preserva texto e não interrompe comandos locais', async ({ page }) => {
  await page.addInitScript(endpoint => localStorage.setItem('jarvis.backend.v1', endpoint), endpoint);
  await page.route(`${endpoint}/**`, route => route.abort('failed'));
  await page.goto('./');
  await page.getByRole('button', { name: 'Preferências' }).click();
  await expect(page.getByRole('dialog')).toContainText('IA indisponível');
  await page.getByRole('button', { name: 'Fechar janela' }).click();
  await page.getByRole('textbox', { name: 'Sua mensagem para JARVIS' }).fill('Explique um buraco negro');
  await page.getByRole('button', { name: 'Enviar mensagem' }).click();
  await expect(page.getByRole('alert')).toContainText('Sem conexão');
  await expect(page.getByRole('textbox', { name: 'Sua mensagem para JARVIS' })).toHaveValue('Explique um buraco negro');
  await page.getByRole('textbox', { name: 'Sua mensagem para JARVIS' }).fill('calcular 4 * 3');
  await page.getByRole('button', { name: 'Enviar mensagem' }).click();
  await expect(page.getByRole('log')).toContainText('O resultado é 12.');
});
